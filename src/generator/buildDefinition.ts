import type { StyleDefinition } from '@dicebear/core';
import { D } from '@mobily/ts-belt';
import { BORDERS } from './borders';
import { COMPONENT, LAYOUT_PARTS, LAYOUT_WEIGHT, MIRRORS, QUARTER } from './compose';
import { LAYOUTS, type Placed, SIZE, THREADS } from './grid';
import type { Library } from './library';
import { DRAWINGS, type Part } from './motifs';
import { PAINT, type Paint } from './paint';
import { PALETTES, type Palette } from './palettes';
import { el, ref, type StyleElement, type StyleVariant } from './styleDefinition';
import { areaPath, strokePath } from './svgPaths';

// Linen notches at each cell's edge midpoints split solid runs into separate crosses; below 36 px they only dull the thread
const STITCH = 'M.55 0h.9L1 .45zM.55 2h.9L1 1.55zM0 .55v.9L.45 1zM2 .55v.9L1.55 1z';
const TEXTURE_FROM_PX = 36;

const ENCODE: Record<Paint['path'], (cells: Placed[]) => string> = {
  stroke: strokePath,
  area: areaPath,
};

function body(cells: Placed[]): StyleElement[] {
  return THREADS.flatMap((t) => {
    const of = cells.filter((p) => p.t === t);
    const paint = PAINT[t];
    return of.length > 0
      ? [el('path', { ...paint.attributes, d: ENCODE[paint.path](of) })]
      : [];
  });
}

function paletteVariant(p: Palette): StyleVariant {
  const s = String(SIZE);
  const id = `t-${p.name}`;
  const elements: StyleElement[] = [
    el('rect', { width: s, height: s, fill: p.canvas }),
    el('defs', {}, [
      el('pattern', { id, width: '2', height: '2', patternUnits: 'userSpaceOnUse' }, [
        el('path', { fill: p.canvas, d: STITCH }),
      ]),
    ]),
    el('g', { stroke: p.a, color: p.b, fill: p.c, 'stroke-width': '0' }, [
      ...MIRRORS.map((transform) => ref('q', transform)),
      el('rect', { class: 't', width: s, height: s, fill: `url(#${id})` }),
      ref('b', ''),
    ]),
  ];
  if (p.rim) {
    elements.push(
      el('circle', {
        cx: '13',
        cy: '13',
        r: '12.7',
        fill: 'none',
        stroke: p.rim,
        'stroke-width': '.6',
      })
    );
  }
  elements.push(
    el('style', {}, [
      {
        type: 'text',
        value: `@media(max-width:${TEXTURE_FROM_PX - 0.1}px){.t{display:none}}`,
      },
    ])
  );
  return {
    weight: 1,
    tags: [`region:${p.region}`, `canvas:${p.rim ? 'dark' : 'linen'}`],
    elements,
  };
}

function variants(
  parts: Record<string, Part>,
  cells: Record<string, Placed[]>
): Record<string, StyleVariant> {
  return D.mapWithKey(parts, (name, part) => ({
    weight: part.weight ?? 1,
    elements: body(cells[name]),
  }));
}

// The palette places the quarter four times; the quarter places its core, both arms and its corner
export function buildDefinition(lib: Library): StyleDefinition {
  const square = { width: SIZE, height: SIZE };
  return {
    $comment:
      'Vyshyvanka quarters: Ukrainian counted-thread ornaments from one mirrored quarter. Generated by src/generator with `pnpm build:style`; never edit it by hand.',
    canvas: { ...square, elements: [ref('p', '')] },
    components: {
      p: {
        ...square,
        variants: Object.fromEntries(PALETTES.map((p) => [p.name, paletteVariant(p)])),
      },
      q: {
        ...square,
        variants: Object.fromEntries(
          LAYOUTS.map((layout) => [
            layout,
            {
              weight: LAYOUT_WEIGHT[layout],
              elements: QUARTER.map(([slot, t]) =>
                ref(COMPONENT[LAYOUT_PARTS[layout][slot]], t)
              ),
            },
          ])
        ),
      },
      ...Object.fromEntries(
        D.keys(COMPONENT).map((kind) => [
          COMPONENT[kind],
          { ...square, variants: variants(DRAWINGS[kind], lib[kind]) },
        ])
      ),
      b: { ...square, probability: 55, variants: BORDERS },
    },
  };
}
